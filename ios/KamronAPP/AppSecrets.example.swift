//
//  Образец. Рабочий файл AppSecrets.swift создаёт скрипт сборки из
//  ссылки восстановления; в репозиторий он не попадает.
//
//  Нужен для одного: при первом запуске у приложения своё пустое
//  хранилище, и без ключа оно не знает, откуда взять накопленное.
//  С ключом оно молча восстанавливается из последней копии.
//
//  Файл собирается только в приложение. В виджет он не попадает —
//  у того свой ключ, которым копии не открываются.
//
enum AppSecrets {
    /// Адрес сервера Jarvis, без косой черты в конце.
    static let server = ""

    /// Главный ключ — тот же, что в ссылке восстановления.
    static let token = ""
}
